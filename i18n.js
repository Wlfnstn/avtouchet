function tr(s) {
  if (LANG !== 'kk' || !s || !/[А-Яа-яЁё]/.test(s)) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s), core = m[2];
  let out = KK_EXACT[core];
  if (out == null) for (const [re, rep] of KK_RE) { re.lastIndex = 0; if (re.test(core)) { out = core.replace(re, rep); break; } }
  if (out == null) {
    let t = core;
    for (const [re, rep] of KK_PART) t = t.replace(re, rep);
    if (t !== core) out = t;
  }
  return out == null ? s : m[1] + out + m[3];
}

